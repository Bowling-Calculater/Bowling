# Builds season.js (bundled static season data) from leaguepals/season.json.
# Only Texas Strangers per-bowler rows are kept; opponent bowler rows are intentionally dropped.
import json, datetime, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
d = json.loads((root / "leaguepals/season.json").read_text())
b = d["bowlers"]; st = d["standings_after_week10"]
def iso(s):
    m, dd, y = s.split("/"); return datetime.date(2000 + int(y), int(m), int(dd)).isoformat()
weeks = []
for w in d["weeks"]:
    rows = b["texas_by_week"][str(w["week"])]
    weeks.append({
        "week": w["week"], "date": iso(w["date"]), "opponent": w["opponent"],
        "points": [w["our_points"], w["opp_points"]],
        "ours": [w["ours"]["g1"], w["ours"]["g2"], w["ours"]["g3"], w["ours"]["series"]],
        "opp": [w["opp"]["g1"], w["opp"]["g2"], w["opp"]["g3"], w["opp"]["series"]],
        "bowlers": [{"name": r["bowler"], "avg": r["avg"], "games": [r["g1"], r["g2"], r["g3"]], "hcp": r["hdcp_per_game"]} for r in rows],
    })
out = {
    "source": "LeaguePals", "league": d["league"], "team": d["team"],
    "standing": {"position": st["position"], "after_week": 10, "ytd": [st["ytd_wins"], st["ytd_loss"]]},
    "roster": [{"name": r["bowler"], "avg": r["avg"], "games": r["total_games"], "pins": r["total_pins"],
                "high_game": r["high_game"], "high_game_hcp": r["high_game_hdcp"],
                "high_series": r["high_series"], "high_series_hcp": r["high_series_hdcp"]} for r in b["texas_season"]],
    "weeks": weeks,
}
(root / "season.js").write_text("// Generated by tools/build-season.py from LeaguePals data (Weeks 1-10). Texas Strangers only.\nexport const SEASON = " + json.dumps(out, separators=(",", ":")) + ";\n")
print("ok", len(weeks))
